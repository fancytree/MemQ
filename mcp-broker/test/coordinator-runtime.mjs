import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';

const base = process.env.COORDINATOR_TEST_URL || 'http://127.0.0.1:18789';
const grant = randomUUID();
async function call(action, owner = 'alice', operation, id = grant, session = 'sealed-v1') {
  const response = await fetch(base, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ grant: id, action, owner, operation, session }) });
  assert.equal(response.status, 200);
  return (await response.json()).result;
}
assert.equal(await call('initialize'), true);
assert.equal(await call('initialize', 'bob'), false);
assert.equal(await call('allows', 'bob'), false);
const starts = await Promise.all(Array.from({ length: 16 }, (_, i) => call('start', 'alice', `op-${i}`)));
assert.equal(starts.filter(Boolean).length, 1);
const winner = `op-${starts.findIndex(Boolean)}`;
assert.equal(await call('revoke', 'bob'), false);
assert.equal(await call('revoke'), true);
assert.equal(await call('complete', 'alice', winner), false);
assert.equal(await call('allows'), false);
assert.equal(await call('initialize'), false);
const second = randomUUID();
assert.equal(await call('initialize', 'alice', undefined, second), true);
assert.equal(await call('allows', 'alice', undefined, second), true);
assert.equal(await call('start', 'alice', 'op', second), 'sealed-v1');
assert.equal(await call('fail', 'alice', 'op', second), true);
assert.equal(await call('start', 'alice', 'retry', second), null);
assert.equal(await call('allows', 'alice', undefined, second), false);
const third = randomUUID();
assert.equal(await call('initialize', 'alice', undefined, third), true);
assert.equal(await call('start', 'alice', 'first', third), 'sealed-v1');
assert.equal(await call('complete', 'alice', 'first', third, 'sealed-v2'), true);
assert.equal(await call('start', 'alice', 'second', third), 'sealed-v2');
const fourth = randomUUID();
assert.equal(await call('sealed-init', 'alice', undefined, fourth), true);
assert.equal(await call('sealed-request', 'alice', undefined, fourth), true);
assert.equal(await call('sealed-request', 'bob', undefined, fourth), false);
assert.equal(await call('sealed-refresh', 'alice', undefined, fourth), true);
assert.equal(await call('sealed-check', 'alice', undefined, fourth), true);
assert.equal(await call('revoke', 'alice', undefined, fourth), true);
assert.equal(await call('sealed-request', 'alice', undefined, fourth), false);
const fifth = randomUUID();
assert.equal(await call('sealed-init', 'alice', undefined, fifth), true);
const pending = call('sealed-slow-refresh', 'alice', undefined, fifth);
let sawRefresh = false;
for (let i = 0; i < 50; i++) {
  if (!await call('allows', 'alice', undefined, fifth)) { sawRefresh = true; break; }
  await new Promise(resolve => setTimeout(resolve, 10));
}
assert.equal(sawRefresh, true, 'refresh never entered pending state');
assert.equal(await call('revoke', 'alice', undefined, fifth), true);
assert.equal(await pending, false);
assert.equal(await call('sealed-request', 'alice', undefined, fifth), false);
const sixth = randomUUID();
assert.equal(await call('exchange-init', 'alice', undefined, sixth), true);
assert.equal(await call('exchange-init', 'alice', undefined, sixth), false);
assert.equal(await call('exchange-refresh', 'alice', undefined, sixth), true);
assert.equal(await call('sealed-check', 'alice', undefined, sixth), true);
const digest = 'a'.repeat(64);
assert.equal(await call('prepare-revoke', 'alice', digest, sixth, 'client'), true);
assert.equal(await call('prepared-revoke', 'alice', digest, sixth, 'client'), true);
assert.equal(await call('prepared-revoke', 'alice', digest, sixth, 'other'), false);
assert.equal(await call('prepared-revoke', 'bob', digest, sixth, 'client'), false);
const seventh = randomUUID();
assert.equal(await call('initialize-bound', 'alice', 'client', seventh), true);
assert.equal(await call('register-issued', 'alice', digest, seventh), true);
assert.equal(await call('has-issued', 'alice', digest, seventh, 'client'), true);
assert.equal(await call('has-issued', 'alice', digest, seventh, 'wrong-client'), false);
assert.equal(await call('revoke', 'alice', undefined, seventh), true);
assert.equal(await call('has-issued', 'alice', digest, seventh, 'client'), false);
assert.equal(await call('register-issued', 'alice', 'b'.repeat(64), seventh), false);
const eighth = randomUUID();
assert.equal(await call('initialize-bound', 'alice', 'client', eighth), true);
assert.equal(await call('register-short', 'alice', digest, eighth), true);
await new Promise(resolve => setTimeout(resolve, 150));
assert.equal(await call('issued-status', 'alice', digest, eighth, 'client'), 'uncertain');
const ninth = randomUUID();
assert.equal(await call('initialize-bound', 'alice', 'client', ninth), true);
assert.equal(await call('register-refresh-short', 'alice', digest, ninth), true);
assert.equal(await call('register-refresh-long', 'alice', 'd'.repeat(64), ninth), true);
await new Promise(resolve => setTimeout(resolve, 250));
assert.equal(await call('issued-status', 'alice', 'd'.repeat(64), ninth, 'client'), 'uncertain');
const tenth = randomUUID();
assert.equal(await call('initialize-pending', 'alice', 'client', tenth), true);
const claims = await Promise.all(Array.from({ length: 16 }, () => call('claim-authorization', 'alice', 'client', tenth)));
assert.equal(claims.filter(Boolean).length, 1);
const eleventh = randomUUID();
assert.equal(await call('initialize-pending', 'alice', 'client', eleventh), true);
assert.equal(await call('revoke', 'alice', undefined, eleventh), true);
assert.equal(await call('claim-authorization', 'alice', 'client', eleventh), false);
console.log('Local Durable Object coordination checks passed');
