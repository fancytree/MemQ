import { readFileSync, writeFileSync } from 'node:fs';
const source = readFileSync(new URL('../../supabase/functions/mcp/tools.ts', import.meta.url), 'utf8');
const output = '// Generated by scripts/sync-tools.mjs; edit the shared source in supabase/functions/mcp/tools.ts.\n' + source.replaceAll('npm:@modelcontextprotocol/server@^2.0.0', '@modelcontextprotocol/server').replaceAll('npm:@supabase/supabase-js@^2', '@supabase/supabase-js').replaceAll('npm:zod@^4.3.6', 'zod');
const target = new URL('../src/tools.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) { console.error('MCP tools are out of sync'); process.exitCode = 1; }
} else writeFileSync(target, output);
