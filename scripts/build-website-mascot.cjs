/** Put the app's mascot rig on the website.
 *
 *   node scripts/build-website-mascot.cjs [--check]
 *
 * The website used to carry its own copy of the character: the paths lifted out of
 * the app's artwork into the page, and the motion re-described as CSS keyframes
 * with the app's numbers typed in beside them. Two descriptions of one character
 * drift, and that one had: it was still the frame-swapping picture after the app
 * had stopped being one.
 *
 * So there is no second description any more. This writes two things, both from
 * components/mascot/rig, and both are regenerated rather than edited:
 *
 * - preview/memq-website/mascot-rig.js — the solver itself, the same code the app
 *   runs every frame, compiled for a browser.
 * - the character's markup in index.html, between the two `mascot` comments — the
 *   SVG the solver drives, drawn in the rest pose so the page shows the character
 *   with no script at all. Each element says which number in a frame it listens to
 *   (`data-m` a matrix, `data-o` an opacity, `data-d` a path, `data-rx` / `data-ry`
 *   a radius), and site.js does nothing but hand them over.
 *
 * `--check` writes nothing and fails if either is out of date.
 */
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');

const root = path.resolve(__dirname, '..');
const RIG = path.join(root, 'components/mascot/rig');
const SITE = path.join(root, 'preview/memq-website');
const OUT_JS = path.join(SITE, 'mascot-rig.js');
const PAGE = path.join(SITE, 'index.html');
const check = process.argv.includes('--check');

/** What the hero is: Today's resting character behind Today's hill, with the sparks
 * the hero has always worn. They are decoration there, not an announcement.
 *
 * `pose` is what the app's Today screen passes the character, and for the same
 * reason: it is leaning on a slope. The hands rest level and are then slid round
 * the outline to where the hill's edge passes each of them, and the tail is lifted
 * clear of the hill. `look` is where the eyes rest when no pointer is leading
 * them: toward the headline, which is to its left. */
const HERO = {
  mood: 'todayIdle', marks: ['spark'], id: 'm',
  pose: { level: true, hands: 1, handOutL: -6, handTurnL: 25, handTurnR: 6, tailX: 6, tailY: -26 },
  look: { x: -0.7, y: 0.1 },
};

/** The two hills, in the character's own 256 square, so they cannot come apart from
 * it however the page is sized: the whole scene is one drawing.
 *
 * Between the points marked below they are the app's own curves — assets/home-figma
 * wave-back and wave-front, placed against the character exactly as Today places
 * them — which is what puts the paws on the edge. Outside that stretch a phone
 * screen ends and a web page does not, so each is carried on to the left and the
 * right as more of the same rolling ground, far past any window. */
const FAR = 6000;
const HILLS = {
  back: {
    fill: '#EEFC41',
    d: `M${-FAR} 118 L-1100 118 C-950 120 -860 82 -720 70 C-600 60 -520 98 -420 110 C-330 120 -270 100 -234.6 74.9`
      // the app's back wave
      + ' C-210.6 54.6 -175.4 43.6 -124.7 55.7 C-61.4 70.8 -45.1 2.8 25.2 38.3 C95.6 73.7 162.4 202.2 225.2 197.6 C270.6 194.2 286.5 226 288 224.7'
      + ` C330 240 420 215 520 225 L${FAR} 225 V2000 H${-FAR} Z`,
  },
  front: {
    fill: 'url(#m-hill)',
    d: `M${-FAR} 178 L-1150 178 C-1000 175 -900 150 -780 150 C-640 150 -560 185 -430 188 C-340 190 -275 164 -234.6 131.4`
      // the app's front wave: its crest, then the slope the character leans on
      + ' C-210.6 112 -152.5 70.9 -100.5 70.9 C-17.4 70.9 -20.9 118.6 49.3 152.5 L51.2 153.4 C120 186.6 145.8 199 222.4 193.6 C272.5 190 296.7 182.5 302.5 179.1'
      + ` C345 155 430 150 520 168 C640 192 800 150 1000 160 L${FAR} 160 V2000 H${-FAR} Z`,
    // the app's gradient, top to bottom of the same hill
    gradient: '<linearGradient id="m-hill" x1="0" y1="85.3" x2="0" y2="428.4" gradientUnits="userSpaceOnUse">'
      + '<stop offset="0.089" stop-color="#FAFE9A"/><stop offset="0.644" stop-color="#EAFB40"/>'
      + '<stop offset="1" stop-color="#EDFC80" stop-opacity="0"/></linearGradient>',
  },
};

// --- The solver, for a browser ---------------------------------------------------

const modules = ['art', 'rig', 'solve'].map((name) => {
  const source = fs.readFileSync(path.join(RIG, `${name}.ts`), 'utf8');
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019, removeComments: true,
    },
  });
  return `  './${name}': function (exports, require) {\n${outputText}\n  },`;
});
const bundle = `/* Generated by scripts/build-website-mascot.cjs from components/mascot/rig. Do not edit. */
(function () {
var modules = {
${modules.join('\n')}
};
var cache = {};
function require(name) {
  if (cache[name]) return cache[name].exports;
  var module = cache[name] = { exports: {} };
  modules[name](module.exports, require);
  return module.exports;
}
var rig = require('./rig'), solve = require('./solve'), art = require('./art');
var api = {
  CH: rig.CH, CHANNEL_COUNT: rig.CHANNEL_COUNT, RIG_ORIGIN: rig.RIG_ORIGIN, RIG_VIEW: rig.RIG_VIEW,
  createRigState: solve.createRigState, solveRig: solve.solveRig, art: art,
};
if (typeof module !== 'undefined' && module.exports) module.exports = api;
else window.MemQMascot = api;
})();
`;

// --- The markup it drives ----------------------------------------------------------

const api = (() => {
  const module = { exports: {} };
  new Function('module', bundle)(module);
  return module.exports;
})();
const { RIG_ART, RIG_INK, RIG_MEASURE } = api.art;

const num = (n) => String(Math.round(n * 1000) / 1000);
const matrix = (m) => `matrix(${m.map(num).join(' ')})`;
const paths = (name) => RIG_ART[name].map((p) => `<path d="${p.d}" fill="${p.fill ?? 'none'}"`
  + (p.stroke ? ` stroke="${p.stroke}" stroke-width="${p.width}"` : '')
  + (p.cap ? ` stroke-linecap="${p.cap}"` : '') + (p.join ? ` stroke-linejoin="${p.join}"` : '') + '/>').join('');

function markup({ mood, marks, id, pose, look }) {
  const tweak = new Array(api.CHANNEL_COUNT).fill(0);
  for (const mark of marks) tweak[api.CH[mark]] = 1;
  const frame = api.solveRig(api.createRigState(mood), {
    mood, still: true, linked: true, drift: false, tweak, dragX: 0, dragY: 0, lookX: 0, lookY: 0,
    blink: 0, wink: 0, beat: 0, poke: 0, pokePart: -1, debug: false, ...pose,
  }, 0);
  // A group placed by one of the frame's matrices, optionally faded by one of its numbers.
  const moved = (key, inner, fade) => `<g data-m="${key}" transform="${matrix(frame[key])}"`
    + (fade ? ` data-o="${fade}" opacity="${num(frame[fade])}"` : '') + `>${inner}</g>`;
  const eye = (side) => {
    const { rx, ry } = side === 'L' ? RIG_MEASURE.eyeL : RIG_MEASURE.eyeR;
    const lid = { x: 60, tall: 100 };
    return moved(`ball${side}`,
      `<ellipse rx="${rx}" ry="${ry}" fill="${RIG_INK.white}"/>`
      + `<g clip-path="url(#${id}-white${side})">${moved(`pupil${side}`, `<ellipse rx="${RIG_MEASURE.pupil.rx}" ry="${RIG_MEASURE.pupil.ry}" fill="${RIG_INK.outline}"/>`)}</g>`
      + `<g clip-path="url(#${id}-lid${side})">`
      + moved(`lid${side}`, `<rect x="${-lid.x}" y="${-lid.tall}" width="${lid.x * 2}" height="${lid.tall}" fill="${RIG_INK.skin}"/>`)
      + moved(`low${side}`, `<rect x="${-lid.x}" y="0" width="${lid.x * 2}" height="${lid.tall}" fill="${RIG_INK.skin}"/>`)
      + '</g>', `white${side}`)
      + moved(`eye${side}`,
        `<path data-d="lash${side}" d="${frame[`lash${side}`]}" data-o="lash${side}O" opacity="${num(frame[`lash${side}O`])}" fill="none" stroke="${RIG_INK.outline}" stroke-width="${RIG_MEASURE.lash.stroke}" stroke-linecap="round"/>`
        + moved(`wink${side}`, paths(`wink${side}`), `wink${side}O`));
  };
  const clips = ['L', 'R'].map((side) => {
    const { rx, ry } = side === 'L' ? RIG_MEASURE.eyeL : RIG_MEASURE.eyeR;
    // The lids are cut off a little outside the white, so they cover its soft edge too.
    return `<clipPath id="${id}-white${side}"><ellipse rx="${rx}" ry="${ry}"/></clipPath>`
      + `<clipPath id="${id}-lid${side}"><ellipse rx="${rx + 1.5}" ry="${ry + 4}"/></clipPath>`;
  }).join('');
  const at = `<g transform="translate(${api.RIG_ORIGIN.x} ${api.RIG_ORIGIN.y})">`;
  // Back to front: the far hill, the half of the character that comes out from
  // behind its own silhouette, the near hill, and then its face and its hands —
  // which is what puts the body behind the hill and the paws over its edge.
  return `<svg class="mascot-art" viewBox="0 0 ${api.RIG_VIEW} ${api.RIG_VIEW}" aria-hidden="true" focusable="false"`
    + ` data-mascot="${mood}" data-marks="${marks.join(' ')}" data-pose='${JSON.stringify(pose)}' data-look="${look.x} ${look.y}">`
    + `<defs>${clips}${HILLS.front.gradient}</defs>`
    // The far hill drifts a little as the page scrolls; the near one may not, since
    // the paws are on it. The number is in this drawing's units per pixel scrolled.
    + `<path class="hill hill-back" data-parallax="0.035" d="${HILLS.back.d}" fill="${HILLS.back.fill}"/>`
    + at
    + `<path data-d="tailD" d="${frame.tailD}" fill="none" stroke="${RIG_INK.outline}" stroke-width="${RIG_MEASURE.tail.stroke}" stroke-linecap="round"/>`
    + moved('tailTip', paths('tailTip')) + moved('hornL', paths('hornL')) + moved('hornR', paths('hornR'))
    + moved('body', `<ellipse data-rx="bodyRx" data-ry="bodyRy" rx="${num(frame.bodyRx)}" ry="${num(frame.bodyRy)}" fill="${RIG_INK.skin}" stroke="${RIG_INK.outline}" stroke-width="${RIG_MEASURE.body.stroke}"/>`)
    + '</g>'
    + `<path class="hill hill-front" d="${HILLS.front.d}" fill="${HILLS.front.fill}"/>`
    + at
    + eye('L') + eye('R')
    + moved('mouth', `<ellipse data-rx="mouthRx" data-ry="mouthRy" rx="${num(frame.mouthRx)}" ry="${num(frame.mouthRy)}" fill="${RIG_INK.outline}"/>`, 'mouthO')
    + moved('mouthArc', paths('mouthArc'), 'mouthArcO')
    + moved('badge', paths('badge'), 'badgeO')
    + `<g data-o="handsO" opacity="${num(frame.handsO)}">${moved('handL', paths('handL'))}${moved('handR', paths('handR'))}</g>`
    + moved('spark', paths('spark'), 'sparkO') + moved('question', paths('question'), 'questionO') + moved('zzz', paths('zzz'), 'zzzO')
    + '</g></svg>';
}

const START = '<!--mascot:start-->', END = '<!--mascot:end-->';
const page = fs.readFileSync(PAGE, 'utf8');
const drawn = `${START}${markup(HERO)}${END}`;
let next;
if (page.includes(START)) {
  next = page.slice(0, page.indexOf(START)) + drawn + page.slice(page.indexOf(END) + END.length);
} else {
  // First run: the hand-placed drawing this replaces.
  const old = /<div class="mascot"><svg class="mascot-art"[\s\S]*?<\/svg><\/div>/;
  if (!old.test(page)) throw new Error('index.html has no mascot to replace');
  next = page.replace(old, `<div class="mascot">${drawn}</div>`);
}

const stale = [];
if (!fs.existsSync(OUT_JS) || fs.readFileSync(OUT_JS, 'utf8') !== bundle) stale.push(path.relative(root, OUT_JS));
if (next !== page) stale.push(path.relative(root, PAGE));
if (check) {
  if (stale.length) { console.error(`Out of date: ${stale.join(', ')}. Run node scripts/build-website-mascot.cjs`); process.exit(1); }
  console.log('The website mascot matches components/mascot/rig.');
} else {
  fs.writeFileSync(OUT_JS, bundle);
  fs.writeFileSync(PAGE, next);
  console.log(stale.length ? `Wrote ${stale.join(', ')}.` : 'Already up to date.');
}
