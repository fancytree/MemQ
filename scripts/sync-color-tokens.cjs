/** Generate all platform token artifacts from canonical TypeScript definitions. */
const fs = require('node:fs');
const { resolve } = require('node:path');
const { loadTheme } = require('./theme-module.cjs');
const { colors, referenceColors, semanticColor, decorationOpacity } = loadTheme('colors');
const { fonts, type, referenceTypography } = loadTheme('typography');
const { layout } = loadTheme('spacing');
const { componentTokens, interaction, elevation, sourceReference } = loadTheme('components');
const { artwork } = loadTheme('artwork');
const kebab = (key) => key.replace(/[A-Z]/g, (v) => `-${v.toLowerCase()}`);
const header = '/* Generated by scripts/sync-color-tokens.cjs. Edit theme/*.ts. */\n';
const colorCSS = header + ':root {\n' +
  Object.entries(colors).filter(([key]) => key !== 'notification').map(([key, value]) => `  --memq-${kebab(key)}: ${value};`).join('\n') +
  '\n' + Object.entries(referenceColors).map(([key, value]) => `  --memq-reference-${kebab(key)}: ${value};`).join('\n') + '\n}\n';
const props = { fontFamily: 'family', fontSize: 'size', lineHeight: 'height', fontWeight: 'weight', letterSpacing: 'tracking' };
const foundationCSS = header + ':root {\n' + Object.entries(type).flatMap(([role, value]) => Object.entries(value).map(([key, v]) =>
  `  --memq-type-${kebab(role)}-${props[key]}: ${typeof v === 'number' ? `${v}px` : `'${v}'`};`)).join('\n') +
  '\n' + Object.entries(layout).map(([key, value]) => `  --memq-space-${kebab(key)}: ${value}px;`).join('\n') + '\n}\n';
const tokens = {
  version: '2.0.0', authority: sourceReference,
  reference: { colors: referenceColors, typography: referenceTypography, decorationOpacity },
  runtime: { semanticColor, colors, typography: type, fonts, layout, componentTokens, interaction, elevation },
  artwork,
  status: { reference: 'Measured in supplied source; not newly inspected or bound Figma variables',
    runtime: 'Implementation aliases; contrast/line-height/navigation-label adaptations and unmeasured interaction states are extensions',
    artwork: 'Four Inkling poses are local exports; remaining entries retain figma-source-only availability' },
};
const artifacts = new Map([
  ['theme/colors.css', colorCSS],
  ['theme/foundations.css', foundationCSS],
  ['theme/native-colors.json', JSON.stringify({ background: colors.bg }, null, 2) + '\n'],
  ['theme/tokens.json', JSON.stringify(tokens, null, 2) + '\n'],
]);
if (require.main === module) {
  for (const [file, expected] of artifacts) {
    const target = resolve(__dirname, '..', file);
    if (process.argv.includes('--check')) {
      if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== expected) {
        console.error(`${file} is stale; run npm run tokens:sync`); process.exitCode = 1;
      }
    } else fs.writeFileSync(target, expected);
  }
}
module.exports = { colors, referenceColors, tokens, kebab };
